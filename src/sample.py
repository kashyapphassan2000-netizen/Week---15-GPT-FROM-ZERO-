"""
src/sample.py - Day 6 deliverable
Load a checkpoint, prime with a prompt, generate N top-p completions, write them to markdown.

    python src/sample.py --ckpt checkpoints/ckpt_final.pt \
        --prompt "Today we are announcing" --n 10 --temperature 0.85 --top_p 0.92 \
        --out data/samples_day6.md
"""

import argparse
import pathlib
import sys
import time
from contextlib import nullcontext

import torch
import torch.nn.functional as F

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
from src.model import filter_logits  # noqa: E402
from src.utils import get_device, load_model_from_ckpt  # noqa: E402


@torch.no_grad()
def generate(model, idx, max_new_tokens, temperature=0.8, top_p=0.92,
             top_k=None, eos_token=None, device="cuda"):
    """idx: (1, T) int64. Returns (1, T + <=max_new_tokens)."""
    model.eval()
    block_size = model.cfg.block_size
    amp = torch.autocast("cuda", dtype=torch.bfloat16) \
        if device.startswith("cuda") and torch.cuda.is_bf16_supported() else nullcontext()
    for _ in range(max_new_tokens):
        idx_cond = idx if idx.size(1) <= block_size else idx[:, -block_size:]
        with amp:
            logits, _ = model(idx_cond)
        logits = logits[:, -1, :].float() / max(temperature, 1e-5)
        logits = filter_logits(logits, top_k=top_k, top_p=top_p)
        probs = F.softmax(logits, dim=-1)
        next_id = torch.multinomial(probs, num_samples=1)
        idx = torch.cat((idx, next_id), dim=1)
        if eos_token is not None and next_id.item() == eos_token:
            break
    return idx


def main():
    import tiktoken

    ap = argparse.ArgumentParser()
    ap.add_argument("--ckpt", default="checkpoints/ckpt_final.pt")
    ap.add_argument("--prompt", default="Today we are announcing")
    ap.add_argument("--n", type=int, default=10)
    ap.add_argument("--max_new_tokens", type=int, default=200)
    ap.add_argument("--temperature", type=float, default=0.85)
    ap.add_argument("--top_p", type=float, default=0.92)
    ap.add_argument("--top_k", type=int, default=None)
    ap.add_argument("--seed", type=int, default=1337)
    ap.add_argument("--out", default="data/samples_day6.md")
    args = ap.parse_args()

    torch.manual_seed(args.seed)
    device = get_device()
    model, ck = load_model_from_ckpt(args.ckpt, device)

    enc = tiktoken.get_encoding("r50k_base")
    prompt_ids = enc.encode(args.prompt)
    x = torch.tensor([prompt_ids], dtype=torch.long, device=device)

    out_path = pathlib.Path(args.out)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with out_path.open("w", encoding="utf-8") as f:
        f.write(f"# Day 6 samples - {time.strftime('%Y-%m-%d %H:%M')}\n\n")
        f.write("> Machine-generated by a 50M-param model trained from scratch. Factually meaningless.\n\n")
        f.write(f"- ckpt: `{args.ckpt}` (step {ck.get('step', '?')}, best val {ck.get('best_val', float('nan')):.4f})\n")
        f.write(f"- prompt: `{args.prompt}`\n")
        f.write(f"- temperature: {args.temperature}  top_p: {args.top_p}  top_k: {args.top_k}\n\n")
        for i in range(args.n):
            y = generate(model, x, args.max_new_tokens, temperature=args.temperature,
                         top_p=args.top_p, top_k=args.top_k, eos_token=enc.eot_token, device=device)
            ids = [t for t in y[0].tolist() if t != enc.eot_token]
            text = enc.decode(ids)
            print(f"\n=== sample {i + 1} ===\n{text}\n")
            f.write(f"## Sample {i + 1}\n\n{text}\n\n---\n\n")
    print(f"[wrote] {out_path}  ({args.n} samples)")


if __name__ == "__main__":
    main()
